/* rez_addr.js — точный ли адрес у кейса (правило от 16.10.2026).

   Адрес вроде «Ступино» или «Одинцовский городской округ» не говорит, где
   проблема, — такие кейсы в резонанс, очаги и СМС не идут. Точный адрес —
   если в нём есть хотя бы:
     * улица (проспект, переулок, шоссе, проезд…);
     * деревня, село, посёлок (кроме «посёлок городского типа X» без улицы —
       это город), хутор…;
     * СНТ, ДНТ, ТСН, ЖК, «территория», садовое/дачное товарищество…;
     * номер дома после населённого пункта или микрорайона
       («Зарайск, 1-й микрорайон, 23», «городок Кубинка-1, к14»).
   На истории за 2 года (50 тыс. адресов) неточными выходит ~3%: город/округ,
   «микрорайон X» без дома, коды дорог, скверы. Проверка — rez/_cmp/precise_test.js.
*/
(function(root){
'use strict';
const STREET=/(^|[\s,])(улица|ул\.?|проспект|пр-кт|пр-т|переулок|пер\.?|шоссе|ш\.|проезд|пр-д|бульвар|б-р|площадь|пл\.|набережная|наб\.|тупик|аллея|линия|просека|квартал|кв-л)(?=[\s,.]|$)/i;
const VILLAGE=/(^|[\s,])(деревня|д\.|село|с\.|поселок|п\.|хутор|станица|слобода|дачный поселок|коттеджный поселок)(?=[\s,.]|$)/i;
const SNT=/(^|[\s,"«])(снт|сот|днт|днп|тсн|снтсн|снп|онт|дпк|кп|жк|жилой комплекс|садов|дачн|огородн|территория|тер\.?|массив|урочище)/i;
// часть адреса — номер дома: «23», «1к2», «13Б», «к14», «3 к1», «20/1», «69 стр 2»
const HOUSE=/^(д\.?\s*|дом\s*|к\.?\s*|корп\.?\s*)?\d+[а-яa-z]?([\/\-]\d+[а-я]?)?(\s*(к|корп|корпус|с|стр|строение)\.?\s*\d+[а-я]?)?$/i;

function precise(addr, shortAddr){
  const short=shortAddr(addr).toLowerCase().replace(/ё/g,'е').replace(/:\s*\[.*$/,'');
  if(STREET.test(short) || SNT.test(short)) return true;
  if(VILLAGE.test(short.replace(/поселок городского типа|рабочий поселок/g,''))) return true;
  const parts=short.split(',').map(s=>s.trim()).filter(Boolean);
  return parts.length>=2 && parts.slice(1).some(p=>HOUSE.test(p));
}

const API={precise};
if(typeof module!=='undefined' && module.exports) module.exports=API; else root.REZADDR=API;
})(typeof window!=='undefined'?window:globalThis);
