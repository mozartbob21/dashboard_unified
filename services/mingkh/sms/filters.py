def thu_current_window(today=None):
    """Текущая, ещё не закрытая отчётная неделя: с ближайшего четверга по сегодня.

    Если сегодня четверг — это один день. Возвращает смещения в днях назад.
    """
    today = today or datetime.date.today()
    back = (today.weekday() - 3) % 7     # 3 = четверг
    return back, 0


def thu_wed_window(today=None):
    """Последняя завершённая отчётная неделя: четверг -> среда.

    Возвращает смещения в днях назад (начало, конец). Если сегодня среда,
    берём предыдущую неделю — текущая ещё не закрыта.
    """
    today = today or datetime.date.today()
    # 2 = среда в нумерации weekday()
    back = (today.weekday() - 2) % 7
    wed = today - datetime.timedelta(days=back or 7)
    end = (today - wed).days
    return end + 6, end          # ровно 7 дней: чт, пт, сб, вс, пн, вт, ср
