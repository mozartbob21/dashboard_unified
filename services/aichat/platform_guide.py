def is_help_request(question):
    q = (question or '').lower().replace('ё', 'е')
    topic = re.search(r'нейрон|платформ|сервис|систем|блок|модул|дашборд|коллективн|мин\s*жкх|зип|сумматор|еддс|чат|доклад|ответственн|опрос|оформлен|доступ|парол', q)
    how = re.search(r'\b(?:как|где|куда|зачем|почему)\b|что уме|какие возможност|как[а-я]* кнопк|инструкци|помоги (?:найти|разобраться)', q)
    return bool(topic and how)


def help_only(question):
    if not is_help_request(question):
        return False
    q = (question or '').lower().replace('ё', 'е')
    # «Как изменились показатели?» is analytics; «Дай инструкцию» is UI help.
    # Do not use interrogatives or the verb «дай» alone as the boundary.
    analysis = re.search(
        r'\b(?:сколько|сравни\w*|проанализируй|динамик\w*|изменил\w*|вырос\w*|снизил\w*)\b'
        r'|\b(?:покажи\w*|дай|дайте|подготовь|сформируй)\s+(?:\w+\s+){0,3}'
        r'(?:отчет\w*|отчёт\w*|сводк\w*|статистик\w*|показател\w*|данн\w*|рейтинг\w*|топ)', q)
    if analysis:
        return False
    return bool(re.search(
        r'\b(?:где|куда)\b|инструкци|что уме|какие возможност'
        r'|\bкак\b.{0,80}\b(?:сохран\w*|откры\w*|найти|назнач\w*|указать|изменить|выбрать|настро\w*|'
        r'пользова\w*|работает|устроен\w*|посмотр\w*|загруз\w*|обнов\w*|удал\w*|созда\w*|ввести|прикреп\w*|добав\w*|получить|вернуться)'
        r'|\bпочему\b.{0,80}\b(?:сохран\w*|откры\w*|кнопк\w*|недоступ\w*|ошибк\w*)', q))



def build(question, allowed_modules, *, is_manager=False):
    if not is_help_request(question):
        return ''
    from core.roles import MODULE_NAMES
    allowed = set(allowed_modules or ())
    lines = [
        'Справка по текущему интерфейсу Нейроны. Это описание возможностей, не статистика и не результат действий.',
        'Главная страница: /. Здесь пользователь открывает доступные ему модули. '
        'Отсутствующий модуль может требовать назначения доступа администратором.',
        'ИИ-чат: /aichat. Кнопки «Новый чат», «Возможности чата», «Навыки», '
        'выбор ИИ-команды и «Обычный чат». Можно задавать общие вопросы, прикладывать файлы '
        'и просить отчёты по сохранённым данным доступных блоков. '
        'Чат не нажимает кнопки и не назначает ответственных: он объясняет действия и готовит тексты.',
        'Оформление меняется в меню «Оформление»; там же режим стекла. '
        'Описание обновлений открывается из меню профиля «Что нового · Версия 3».',
        'Доступные этому аккаунту блоки: ' + (', '.join(MODULE_NAMES[m] for m in MODULE_NAMES if m in allowed) or 'не назначены') + '.',
    ]
    for module, (url, description) in _WORKFLOWS.items():
        if module in allowed:
            lines.append(MODULE_NAMES[module] + ' (' + url + '): ' + description)
    if is_manager:
        lines.append('Администрирование: /users. Разделы «Пользователи и права», «Статистика», '
                     '«Обратная связь», «Логины и пароли». Индивидуальная активность — в карточке пользователя; '
                     'рейтинг посещений всех блоков — в «Статистика». Пароли вводятся в админ-панели, не в чате.')
        if 'collective' in allowed:
            lines.append('В коллективных жалобах администратор управляет справочником через кнопку «Ответственные»; '
                         'добавляет, архивирует и восстанавливает записи. Архивирование сохраняет прежние назначения.')
    lines.append('Не выдумывай отсутствующие в справке кнопки и возможности. Если точного пути здесь нет, '
                 'сообщи об этом. Справка не подтверждает доступность внешнего портала сейчас.')
    return '\n'.join(lines)
