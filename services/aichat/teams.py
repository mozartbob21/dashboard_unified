_ROLE_BY_ID = {role["id"]: role for role in ROLES}
_PRESET_BY_ID = {preset["id"]: preset for preset in PRESETS}


def normalize_team(selection):
    """Validate only allowlisted IDs; reject client-supplied prompt definitions."""
    if selection is None:
        return None
    if not isinstance(selection, dict) or set(selection) - {"preset", "roles"}:
        raise ValueError("Некорректные параметры ИИ-команды.")
    preset = selection.get("preset", "custom")
    if not isinstance(preset, str) or preset not in _PRESET_BY_ID:
        raise ValueError("Неизвестный состав ИИ-команды.")
    roles = selection.get("roles")
    if roles is None and "roles" not in selection and preset != "custom":
        roles = _PRESET_BY_ID[preset]["roles"]
    if not isinstance(roles, list) or not 1 <= len(roles) <= len(ROLES):
        raise ValueError("Выберите от 1 до 11 ролей ИИ-команды.")
    if any(not isinstance(role, str) or role not in _ROLE_BY_ID for role in roles):
        raise ValueError("Неизвестная роль ИИ-команды.")
    if len(set(roles)) != len(roles):
        raise ValueError("Роли ИИ-команды не должны повторяться.")
    if preset != "custom" and set(roles) != set(_PRESET_BY_ID[preset]["roles"]):
        raise ValueError("Изменённый состав должен использовать preset custom.")
    # Stable catalog order makes storage and equality independent of click order.
    return {"preset": preset, "roles": [role["id"] for role in ROLES if role["id"] in roles]}


def public_catalog():
    """Return fresh public metadata, never model instructions."""
    return {
        "roles": [{key: value for key, value in role.items() if key != "prompt"} for role in ROLES],
        "presets": deepcopy(PRESETS),
    }


def build_team_prompt(team):
    """Build model instructions exclusively from trusted, allowlisted roles."""
    team = normalize_team(team)
    if team is None:
        return ""
    parts = [COORDINATOR_PROMPT, "Выбранные профессиональные перспективы:"]
    for role_id in team["roles"]:
        role = _ROLE_BY_ID[role_id]
        parts.append(role["name"] + ": " + role["prompt"])
    return "\n\n".join(parts)
