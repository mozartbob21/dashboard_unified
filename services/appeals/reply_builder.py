def build_empathy_block(analysis: dict, item_id: str = "", mode: str = None,
                                   original_text: str = "", subject: str = "") -> str:
    """
    Собирает эмпатичный абзац.
    - algo: только алгоритм
    - qwen/auto: Qwen анализирует обращение и генерирует блок (с fallback на algo)
    """
    analysis = analysis or {}
    seed = _seed_from_id(item_id)

    # Нормализуем эмоцию
    raw_emotion = _normalize_key(analysis.get("emotion_class") or "NEUTRAL")
    emotion = EN_RU_MAPPING.get(raw_emotion, raw_emotion)
    if emotion not in EMOTION_CORE:
        emotion = "NEUTRAL"

    # Данные контекста
    social_class = str(analysis.get("social_class") or "Житель")
    is_repeated = bool(analysis.get("is_repeated"))
    is_collective = bool(analysis.get("isCollective"))
    duration_days = analysis.get("duration_days") or 0
    criticality = _normalize_key(analysis.get("criticality_level") or "НИЗКИЙ")
    priority = str(analysis.get("priority_level") or "planned")
    if priority not in ACTION_CLOSERS:
        priority = "planned"

    # ── СЛОЙ 1: опенер по соцгруппе ──
    opener = ""
    # social_class может быть списком через запятую — берём первую распознанную группу
    for group in [g.strip() for g in social_class.split(",")]:
        if group in SOCIAL_OPENERS:
            opener = _pick(SOCIAL_OPENERS[group], seed)
            break

    # ── СЛОЙ 2: ядро эмоции ──
    core = _pick(EMOTION_CORE[emotion], seed // 7)

    # Собираем первое предложение: опенер + ядро
    if opener:
        sentence1 = opener + core + "."
    else:
        sentence1 = _capitalize_first(core) + "."

    parts = [sentence1]

    # ── СЛОЙ 3: контекстные вставки (приоритетный порядок, максимум 1-2) ──
    context_added = 0
    MAX_CONTEXT = 2

    if is_repeated and context_added < MAX_CONTEXT:
        parts.append(_pick(CONTEXT_REPEATED, seed // 11))
        context_added += 1

    if criticality in ("ВЫСОКИЙ", "МАКСИМАЛЬНЫЙ") and context_added < MAX_CONTEXT:
        parts.append(_pick(CONTEXT_CRITICAL_HIGH, seed // 13))
        context_added += 1
    elif duration_days and duration_days >= DURATION_LONG_THRESHOLD_DAYS and context_added < MAX_CONTEXT:
        parts.append(_pick(CONTEXT_DURATION_LONG, seed // 13))
        context_added += 1

    if is_collective and context_added < MAX_CONTEXT:
        parts.append(_pick(CONTEXT_COLLECTIVE, seed // 17))
        context_added += 1

    # ── СЛОЙ 4: заверение в действии ──
    # Для NEUTRAL без критичности закрывающая фраза мягче — оставляем planned-тон
    parts.append(_pick(ACTION_CLOSERS[priority], seed // 19))

    algo_block = " ".join(p.strip() for p in parts if p.strip())

    # ── Режим: algo / qwen / auto ──
    resolved_mode = (mode or _os.getenv("EMPATHY_BACKEND", "auto")).strip().lower()
    if resolved_mode == "algo":
        return algo_block

    # Метаданные для Qwen (уже вычислены алгоритмом)
    meta = {
        "algo_emotion": analysis.get("emotion_class", "NEUTRAL"),
        "social_class": analysis.get("social_class", "Житель"),
        "criticality": analysis.get("criticality_level", "НИЗКИЙ"),
        "priority": analysis.get("priority_level", "planned"),
        "duration": analysis.get("duration_days") or "—",
        "is_repeated": bool(analysis.get("is_repeated")),
        "is_collective": bool(analysis.get("isCollective")),
    }

    # Qwen АНАЛИЗИРУЕТ обращение и ГЕНЕРИРУЕТ блок
    ai_block = build_empathy_block_ai(original_text, subject, meta)
    if ai_block:
        return ai_block

    # Любой сбой Qwen → алгоритмический блок (всегда корректен)
    return algo_block


