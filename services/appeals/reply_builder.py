def get_empathy_block(emotion_class: str, item: dict = None) -> str:
    """
    Выбирает одну эмпатийную фразу из пула для данной эмоции.
    Выбор стабилен для одного item_id.
    """
    normalized_class = _normalize_key(emotion_class or "neutral")
    final_class = EN_RU_MAPPING.get(normalized_class, normalized_class)

    if final_class not in OFFICIAL_EMPATHY_VARIATIONS:
        final_class = "NEUTRAL"

    variations = OFFICIAL_EMPATHY_VARIATIONS[final_class]

    item_id = ""
    if item and isinstance(item, dict):
        item_id = str(item.get("request_id") or item.get("id") or "")

    idx = _stable_index(item_id, len(variations))
    return variations[idx]


def generate_reply_from_template(template_text, facts_text, item):
    """
    Берёт загруженный проект ответа (template_text) и вставляет в него
    эмпатийный блок.

    Логика вставки:
    1. Если в тексте есть плейсхолдер {{ empathy_block }} — подставляет туда.
    2. Если нет — вставляет эмпатию после приветствия (строка с "Уважаем" или "!")
       или в самое начало текста.

    Также подставляет {{ facts }} если есть.
    """
    item = item or {}
    analysis = item.get("analysis_data") or {}
    emotion_class = analysis.get("emotion_class") or "neutral"

    empathy = get_empathy_block(emotion_class, item=item)

    text = template_text or ""

    # Подстановка facts если есть плейсхолдер
    if "{{ facts }}" in text and facts_text:
        text = text.replace("{{ facts }}", facts_text)

    # Подстановка эмпатии
    if "{{ empathy_block }}" in text:
        text = text.replace("{{ empathy_block }}", empathy)
    else:
        # Вставляем эмпатию после приветствия или в начало
        text = _insert_empathy(text, empathy)

    return _cleanup_reply_text(text)


def _insert_empathy(text: str, empathy: str) -> str:
    """
    Вставляет эмпатийный блок после строки-приветствия
    (строка с «Уважаемый», заканчивающаяся на «!»), или в самое начало.
    """
    lines = text.split("\n")

    # Ищем строку-приветствие
    insert_pos = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped and (
            stripped.lower().startswith("уважаем")
            or (stripped.endswith("!") and i < 3)
        ):
            insert_pos = i + 1
            break

    # Вставляем эмпатию
    lines.insert(insert_pos, "")
    lines.insert(insert_pos + 1, empathy)
    lines.insert(insert_pos + 2, "")

    return "\n".join(lines)


