def _normalize_key(value):
    return str(value or "").strip().upper().replace("Ё", "Е")


def _cleanup_reply_text(text):
    text = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _stable_index(item_id: str, pool_size: int) -> int:
    """Стабильный индекс на основе хеша ID обращения."""
    if not item_id or pool_size <= 0:
        return 0
    h = hashlib.md5(str(item_id).encode()).hexdigest()
    return int(h, 16) % pool_size


