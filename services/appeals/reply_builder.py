# Корректный официальный шаблон ответа без юридических канцеляризмов и ложного самобичевания
DEFAULT_REPLY_TEMPLATE = """{{ empathy_block }}

По существу Вашего обращения хотим сообщить следующее:
{{ facts }}

В настоящее время технические службы и ответственные организации уже сориентированы на проведение необходимых мероприятий по Вашему адресу для стабилизации ситуации в кратчайшие сроки. Мы держим данный вопрос на контроле и будем информировать Вас о ходе выполнения работ.

С уважением,
Администрация городского округа
"""

def _normalize_text(value):
    return str(value or "").strip()

def _normalize_key(value):
    return _normalize_text(value).upper().replace("Ё", "Е")

def _cleanup_reply_text(text):
    text = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()

def get_empathy_block(emotion_class, item=None):
    """
    Выбирает ровно ОДНО аккуратное дипломатичное предложение из 5 доступных для данной эмоции.
    Использует хеш-сумму request_id для ротации ответов, исключая повторения в разных письмах.
    """
    normalized_class = _normalize_key(emotion_class or "neutral")

    # Англо-русский маппинг для совместимости с кодом анализатора
    en_ru_mapping = {
        "ANGRY": "ГНЕВ",
        "ANXIOUS": "СТРАХ",
        "SAD": "ОТЧАЯНИЕ",
        "URGENT": "ОТЧАЯНИЕ",
        "THANKFUL": "NEUTRAL",
        "NEUTRAL": "NEUTRAL"
    }

    final_class = normalized_class
    if final_class in en_ru_mapping:
        final_class = en_ru_mapping[final_class]

    if final_class not in OFFICIAL_EMPATHY_VARIATIONS:
        final_class = "NEUTRAL"

    variations = OFFICIAL_EMPATHY_VARIATIONS[final_class]

    # Ротация на основе уникального ID обращения
    item_id = ""
    if item and isinstance(item, dict):
        item_id = item.get("request_id") or item.get("id") or ""

    if item_id:
        # Получаем стабильный индекс от 0 до 4 на основе символов ID обращения
        idx = sum(ord(char) for char in str(item_id)) % len(variations)
    else:
        idx = 0

    return variations[idx]

def generate_reply_from_template(template_text, facts_text, item):
    """
    Формирует финальный текст официального ответа.
    """
    template_text = template_text or DEFAULT_REPLY_TEMPLATE

    if not facts_text:
        facts_text = "Специалистами профильных ведомств инициирован выезд по указанному Вами адресу для обследования инженерных сетей и выявления причин неполадок."

    item = item or {}
    analysis = item.get("analysis_data") or {}
    emotion_class = analysis.get("emotion_class", "neutral")

    empathy_block = get_empathy_block(emotion_class, item=item)

    replacements = {
        "{{ request_id }}": item.get("request_id", ""),
        "{{ subject }}": item.get("subject", ""),
        "{{ sender_email }}": item.get("sender_email", ""),
        "{{ facts }}": facts_text,
        "{{ empathy_block }}": empathy_block,

        # Полное сокрытие внутренних скоринговых метрик от заявителя
        "{{ emotion_class }}": "",
        "{{ emotion_label }}": "",
        "{{ criticality_level }}": "",
        "{{ criticality_label }}": "",
        "{{ address }}": analysis.get("address", ""),
        "{{ priority_label }}": "",
        "{{ final_index }}": "",
    }

    result = template_text
    for key, value in replacements.items():
        result = result.replace(key, str(value or ""))

    return _cleanup_reply_text(result)
