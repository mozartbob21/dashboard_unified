def _normalize_key(value):
    return str(value or "").strip().upper().replace("Ё", "Е")


def _cleanup_reply_text(text):
    text = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _pick(pool, seed_int):
    """Детерминированный выбор из пула по числовому seed."""
    if not pool:
        return ""
    return pool[seed_int % len(pool)]


def _seed_from_id(item_id: str) -> int:
    if not item_id:
        return 0
    h = hashlib.md5(str(item_id).encode()).hexdigest()
    return int(h, 16)


def _capitalize_first(s: str) -> str:
    s = s.lstrip()
    if not s:
        return s
    return s[0].upper() + s[1:]


